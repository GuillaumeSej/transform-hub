// Référence temporelle du scénario démo (voir DEMO_NOW dans lib/engine.ts) : 2026-06-22.
// Les statuts sont dérivés de la date planifiée : les échéances passées sont majoritairement
// réalisées, les échéances récentes en cours, les futures planifiées. Le mock couvre désormais
// plusieurs années fiscales (2026-2028) pour illustrer les filtres FY du dashboard.
function movementStatus(
  plannedYear: number,
  plannedMonth: number,
  seq: number
): { status: WorkforceMovement["status"]; actual: boolean; validated: boolean } {
  const isPastYear = plannedYear < 2026;
  const isCurrentYearPast = plannedYear === 2026 && plannedMonth <= 4;
  const isCurrentYearRecent = plannedYear === 2026 && plannedMonth <= 6;
  const isFuture = plannedYear > 2026 || (plannedYear === 2026 && plannedMonth > 6);

  if (isPastYear || isCurrentYearPast) {
    if (seq % 5 === 0) return { status: "À faire", actual: false, validated: false };
    return { status: "Réalisé", actual: true, validated: seq % 3 !== 0 };
  }
  if (isCurrentYearRecent) {
    if (seq % 3 === 0) return { status: "Réalisé", actual: true, validated: false };
    return { status: "À faire", actual: false, validated: false };
  }
  if (isFuture) return { status: "Planifié", actual: false, validated: false };
  return { status: "Planifié", actual: false, validated: false };
}

function generateMovements(employees: Employee[]): WorkforceMovement[] {
  const movements: WorkforceMovement[] = [];
  const used = new Set<string>();
  let seq = 0;

  const pickEmployee = (dept: string, offset: number): Employee => {
    const pool = employees.filter((e) => e.department === dept && !used.has(e.id));
    const emp = pool[(offset * 5) % pool.length];
    used.add(emp.id);
    return emp;
  };

  /** Programme de rattachement standard pour tous les mouvements de démo. Aligné sur
   *  `TEST_PROGRAM.id = "p1"` (voir lib/firestore/admin.ts) — c'est le programme réellement
   *  seedé dans la collection Firestore multi-programmes `programs`, qui alimente le sélecteur
   *  du dashboard RH ET du dashboard exécutif. L'ancien `PRG-2026` (id de `ProgramConfig`, slot
   *  mono-programme historique) rendait tous les mouvements invisibles au sélecteur multi. */
  const DEMO_PROGRAM_ID = "p1";

  /** Génère un léger écart entre lockedPlan et reforecast pour rendre les KPI vivants : le
   *  reforecast est ajusté sur les coûts et parfois sur le salaryImpact, comme dans la vraie vie
   *  (dérive coûts sociaux, indemnités renégociées). Basé sur seq pour rester déterministe. */
  const makeSnapshots = (
    fte: number,
    salaryImpact: number,
    savings: number,
    cost: number,
    seqSnap: number
  ): {
    lockedPlan: WorkforceMovement["lockedPlan"];
    reforecast: WorkforceMovement["reforecast"];
  } => {
    const lockedPlan = { fte, salaryImpact, savings, cost };
    const drift = 0.05 + ((seqSnap * 7) % 15) / 100; // 5-20% de dérive
    const forecastCost = Math.round(cost * (1 + drift));
    // Salary impact reste souvent stable, sauf pour ~1/4 des mouvements
    const forecastSalary =
      seqSnap % 4 === 0
        ? Math.round(salaryImpact * (1 - 0.05 - (seqSnap % 3) / 100))
        : salaryImpact;
    const reforecast = {
      fte,
      salaryImpact: forecastSalary,
      savings: Math.max(0, -forecastSalary),
      cost: forecastCost,
    };
    return { lockedPlan, reforecast };
  };

  const push = (
    emp: Employee | null,
    label: string,
    plan: {
      leverId: string;
      dept: string;
      country?: string;
      workstream?: string;
      functionArea?: string;
    },
    type: WorkforceMovement["type"],
    fte: number,
    year: number,
    month: number,
    opts: {
      toDept?: string;
      pse?: boolean;
      socialScheme?: SocialScheme;
      salaryImpact: number;
      savings: number;
      cost: number;
      requiresRetraining?: boolean;
    }
  ) => {
    seq += 1;
    const day = String(1 + ((seq * 3) % 27)).padStart(2, "0");
    const plannedDate = `${year}-${String(month).padStart(2, "0")}-${day}`;
    const st = movementStatus(year, month, seq);
    // Quelques mouvements annulés restent visibles dans la synthèse mais sont exclus des
    // prévisions/KPI par `isActiveMovement` (répartition déterministe, ~1 sur 17).
    const status = !st.actual && seq % 17 === 0 ? "Abandonné" : st.status;
    const { lockedPlan, reforecast } = makeSnapshots(
      fte,
      opts.salaryImpact,
      opts.savings,
      opts.cost,
      seq
    );
    movements.push({
      id: `MV${String(seq).padStart(3, "0")}`,
      empId: emp?.id ?? null,
      label,
      leverId: plan.leverId,
      workstream: plan.workstream,
      function: plan.functionArea,
      programId: DEMO_PROGRAM_ID,
      type,
      fte,
      department: plan.dept,
      toDepartment: opts.toDept,
      country: emp?.country ?? plan.country ?? "France",
      hrOwner: emp?.hrOwner ?? "Nadia Benali",
      plannedDate,
      actualDate: st.actual ? plannedDate : null,
      status,
      hrValidated: st.validated,
      inPSE: opts.pse,
      socialScheme: opts.socialScheme,
      salaryImpact: opts.salaryImpact,
      savings: opts.savings,
      cost: opts.cost,
      ...(opts.requiresRetraining ? { requiresRetraining: true as const } : {}),
      lockedPlan,
      reforecast,
    });
  };

  /** Étale les mouvements sur 3 années fiscales (2026, 2027, 2028) via un compteur global
   *  déterministe : le mouvement #N est placé sur `2026 + (N % 3)`, ce qui garantit
   *  ~33% par année quelle que soit la taille du plan individuel (l'ancienne distribution
   *  par sous-catégorie produisait des plans à zéro mouvement 2026 quand `forcedDeparture < 3`).
   *  Le mois est également dérivé du compteur pour couvrir 1-12 (débordement autorisé au-delà
   *  de décembre → passe à l'année suivante, ce qui rend la répartition encore plus naturelle). */
  let movementYearCursor = 0;
  const nextYearMonth = (startMonth: number): { year: number; month: number } => {
    const seqYear = 2026 + (movementYearCursor % 3);
    // Le mois de base démarre à `startMonth` et progresse par pas de 2 en tournant sur 12 pour
    // éviter que tous les mouvements d'un même plan tombent le même mois.
    const rawMonth = startMonth + Math.floor(movementYearCursor / 3) * 2;
    const month = ((rawMonth - 1) % 12) + 1;
    movementYearCursor += 1;
    return { year: seqYear, month };
  };

  for (const plan of MOVEMENT_PLAN) {
    const planContext = {
      leverId: plan.leverId,
      dept: plan.dept,
      workstream: plan.workstream,
      functionArea: plan.functionArea,
    };
    // Départs forcés (ancienne "Suppression") — indemnités majorées pour la contrainte.
    for (let i = 0; i < plan.forcedDeparture; i++) {
      const emp = pickEmployee(plan.dept, seq + i);
      const { year, month } = nextYearMonth(plan.startMonth);
      const baseCost = plan.pse ? 45000 + ((seq * 7) % 4) * 5000 : 20000;
      const socialScheme: SocialScheme = plan.pse
        ? "PSE"
        : (["RC", "RCC", "PDV"] as SocialScheme[])[seq % 3];
      push(emp, emp.name, planContext, "Départ forcé", emp.fte, year, month, {
        pse: plan.pse,
        socialScheme,
        salaryImpact: -emp.salary,
        savings: emp.salary,
        cost: Math.round(baseCost * 1.2),
      });
    }
    // Attrition (départ volontaire — préavis seul, pas d'indemnité de rupture).
    for (let i = 0; i < (plan.attrition ?? 0); i++) {
      const emp = pickEmployee(plan.dept, seq + i);
      const { year, month } = nextYearMonth(plan.startMonth + 2);
      push(emp, emp.name, planContext, "Attrition", emp.fte, year, month, {
        salaryImpact: -emp.salary,
        savings: emp.salary,
        cost: Math.round(emp.salary * (0.5 / 12)),
      });
    }
    // Transferts entrants (mobilité interne, formation courte).
    for (let i = 0; i < plan.transferIn; i++) {
      const emp = pickEmployee(plan.dept, seq + i);
      const { year, month } = nextYearMonth(plan.startMonth + 1);
      push(emp, emp.name, planContext, "Transfert entrant", emp.fte, year, month, {
        toDept: plan.toDept,
        salaryImpact: 0,
        savings: 0,
        cost: 8000,
      });
    }
    // Transferts avec reconversion (formation lourde — flag requiresRetraining).
    for (let i = 0; i < plan.retraining; i++) {
      const emp = pickEmployee(plan.dept, seq + i);
      const { year, month } = nextYearMonth(plan.startMonth + 2);
      push(emp, emp.name, planContext, "Transfert entrant", emp.fte, year, month, {
        toDept: plan.toDept,
        salaryImpact: -Math.round(emp.salary * 0.1),
        savings: Math.round(emp.salary * 0.1),
        cost: 15000,
        requiresRetraining: true,
      });
    }
    // Transferts sortants (sortie du périmètre monitoré).
    for (let i = 0; i < (plan.transferOut ?? 0); i++) {
      const emp = pickEmployee(plan.dept, seq + i);
      const { year, month } = nextYearMonth(plan.startMonth + 3);
      push(emp, emp.name, planContext, "Transfert sortant", emp.fte, year, month, {
        toDept: plan.toDept,
        salaryImpact: 0,
        savings: 0,
        cost: 5000,
      });
    }
  }

  for (let i = 0; i < RECRUITMENTS.length; i++) {
    const rec = RECRUITMENTS[i];
    const { year, month } = nextYearMonth(rec.month);
    push(
      null,
      rec.label,
      {
        leverId: rec.leverId,
        dept: rec.dept,
        country: rec.country,
        workstream: rec.workstream,
        functionArea: rec.functionArea,
      },
      "Recrutement",
      rec.fte,
      year,
      month,
      {
        salaryImpact: rec.salary,
        savings: 0,
        cost: 20000,
      }
    );
  }

  return movements;
}

